    private void BTEditarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_BTEditarActionPerformed
        //hacer el metodo para editar parecido al de empleados
        try {
                        
            if (TFIdProducto.getText().trim().isEmpty() || !TFIdProducto.getText().matches("\\d+")) {
                JOptionPane.showMessageDialog(null, "ID de empleado inválido.");
                return;
            }

            if (TFNombreProducto.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Nombre de producto inválido.");
                return;
            }

            if (TFTipoProducto.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Tipo de producto inválido.");
                return;
            }

            if (TFFechaProduccion.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Fecha de producción inválida.");
                return;
            }

            if (TFFechaExpiracion.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Fecha de expiración inválida.");
                return;
            }

            if (TFPrecio.getText().trim().isEmpty() || !TFPrecio.getText().matches("\\d+(\\.\\d+)?")) {
                JOptionPane.showMessageDialog(null, "Precio inválido.");
                return;
            }

            if (TFIdIngredientePrincipal.getText().trim().isEmpty() || !TFIdIngredientePrincipal.getText().matches("\\d+")) {
                JOptionPane.showMessageDialog(null, "ID de ingrediente principal inválido.");
                return;
            }

            producto.setIdProducto(Integer.parseInt(TFIdProducto.getText()));
            producto.setNombreProducto(TFNombreProducto.getText());
            producto.setTipoProducto(TFTipoProducto.getText());
            producto.setFechaProduccion(new SimpleDateFormat("yyyy-MM-dd").parse(TFFechaProduccion.getText()));
            producto.setFechaExpiracion(new SimpleDateFormat("yyyy-MM-dd").parse(TFFechaExpiracion.getText()));
            producto.setPrecio(Float.parseFloat(TFPrecio.getText()));
            ingrediente.setIdIngredientePrincipal(Integer.parseInt(TFIdIngredientePrincipal.getText()));
            producto.setIdIngredientePrincipal(ingrediente);

            updateProducto(producto);
            updateIdIngredientePrincipal(ingrediente);


            bloquearControles();
            JOptionPane.showMessageDialog(null, "Editado Correctamente");
            rellenarTabla();

            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e + " Error");
        }
    }

    public void updateProducto(Productos producto) {
        String sql = "UPDATE productos SET nombreProducto=?, tipoProducto=?, fechaProduccion=?, fechaExpiracion=?, precio=?, idIngredientePrincipal=? WHERE idProducto=?";
        try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/medicinanatural", "root",
                "rootsito");
                PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, producto.getNombreProducto());
            pstmt.setString(2, producto.getTipoProducto());
            pstmt.setDate(3, new java.sql.Date(producto.getFechaProduccion().getTime()));
            pstmt.setDate(4, new java.sql.Date(producto.getFechaExpiracion().getTime()));
            pstmt.setFloat(5, producto.getPrecio());
            pstmt.setInt(6, producto.getIdIngredientePrincipal().getIdIngredientePrincipal());
            pstmt.setInt(7, producto.getIdProducto());

            pstmt.executeUpdate();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    public void updateIdIngredientePrincipal(Ingredientesprincipales ingrediente) {
        String sql = "UPDATE ingredientesprincipales SET idIngredientePrincipal=? WHERE idIngredientePrincipal=?";
        try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/medicinanatural", "root",
                "rootsito");
                PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setInt(1, ingrediente.getIdIngredientePrincipal());
            pstmt.setInt(2, ingrediente.getIdIngredientePrincipal());

            pstmt.executeUpdate();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

       
