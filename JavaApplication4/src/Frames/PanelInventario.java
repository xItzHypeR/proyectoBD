    public void rellenarTabla() {
        String columna[] = {"ID Producto", "Nombre Producto", "Tipo Producto", "Fecha Produccion", "Caduca",
            "Precio", "ID Ingrediente Principal"};
        DefaultTableModel modelo = new DefaultTableModel(columna, 0);
        Object[] obj = new Object[7];
        List<Productos> ls;
        try {
            ls = ctrproductos.findProductosEntities();
            for (Productos producto : ls) {
                obj[0] = producto.getIdProducto();
                obj[1] = producto.getNombreProducto();
                obj[2] = producto.getTipoProducto();
                obj[3] = producto.getFechaProduccion();
                obj[4] = producto.getFechaExpiracion();
                obj[5] = producto.getPrecio();
                // Verificar si idIngredientePrincipal es null antes de acceder a él
                obj[6] = producto.getIdIngredientePrincipal() != null ? producto.getIdIngredientePrincipal().getIdIngredientePrincipal() : "N/A";
    
                modelo.addRow(obj);
            }
    
            jtInventario.setModel(modelo);
            jtInventario.setAutoCreateRowSorter(true);
            TableRowSorter<DefaultTableModel> sorter = new TableRowSorter<>(modelo);
            jtInventario.setRowSorter(sorter);
    
            // Mover MouseListener fuera del bucle
            jtInventario.addMouseListener(new MouseAdapter() {
                public void mousePressed(MouseEvent mouseEvent) {
                    if (mouseEvent.getClickCount() == 2) {
                        TFIdProducto.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 0).toString());
                        TFNombreProducto.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 1).toString());
                        TFTipoProducto.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 2).toString());
                        TFFechaProduccion.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 3).toString());
                        TFFechaExpiracion.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 4).toString());
                        TFPrecio.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 5).toString());
                        TFIdIngredientePrincipal.setText(jtInventario.getValueAt(jtInventario.getSelectedRow(), 6).toString());
    
                        activarEditar();
                    }
                }
            });
    
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e + " Error");
        }
    }



